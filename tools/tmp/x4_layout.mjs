/** Every face-to-face gap, prop-to-prop and prop-to-wall. `ap_reach.mjs:faceGaps` in
 *  structure; the thresholds are this size's, not 1400x1000's. */
export function gapFaults(arena, lo = GAP_SLIT_MAX, hi = GAP_CORRIDOR_MIN, minRun = GAP_SLIT_MAX) {
  const out = [];
  const B = arena.cover;
  const add = (a, b, axis, gap, run, at) => { if (gap > lo && gap < hi && run >= minRun) out.push({ a, b, axis, gap: +gap.toFixed(1), run: +run.toFixed(1), at }); };
  for (let i = 0; i < B.length; i++) {
    for (let j = i + 1; j < B.length; j++) {
      const A = B[i], C = B[j];
      const ovY = Math.min(A.y + A.h / 2, C.y + C.h / 2) - Math.max(A.y - A.h / 2, C.y - C.h / 2);
      const ovX = Math.min(A.x + A.w / 2, C.x + C.w / 2) - Math.max(A.x - A.w / 2, C.x - C.w / 2);
      if (ovY > 0) add(A, C, 'x', Math.abs(A.x - C.x) - (A.w + C.w) / 2, ovY, [(A.x + C.x) / 2, (A.y + C.y) / 2]);
      if (ovX > 0) add(A, C, 'y', Math.abs(A.y - C.y) - (A.h + C.h) / 2, ovX, [(A.x + C.x) / 2, (A.y + C.y) / 2]);
    }
    const A = B[i];
    add(A, { kind: 'WALL west' }, 'x', A.x - A.w / 2, A.h, [A.x - A.w / 2, A.y]);
    add(A, { kind: 'WALL east' }, 'x', arena.width - (A.x + A.w / 2), A.h, [A.x + A.w / 2, A.y]);
    add(A, { kind: 'WALL north' }, 'y', A.y - A.h / 2, A.w, [A.x, A.y - A.h / 2]);
    add(A, { kind: 'WALL south' }, 'y', arena.height - (A.y + A.h / 2), A.w, [A.x, A.y + A.h / 2]);
  }
  return out.sort((p, q) => p.gap - q.gap);
}

/** Two cover boxes that intersect are a MESH CLIP — `arena_probe --audit` exits non-zero. */
export function overlapFaults(arena) {
  const out = [];
  const B = arena.cover;
  for (let i = 0; i < B.length; i++) for (let j = i + 1; j < B.length; j++) {
    const A = B[i], C = B[j];
    if (Math.abs(A.x - C.x) < (A.w + C.w) / 2 - 1e-9 && Math.abs(A.y - C.y) < (A.h + C.h) / 2 - 1e-9) {
      out.push(`${A.kind}@${A.x},${A.y} x ${C.kind}@${C.x},${C.y}`);
    }
  }
  return out;
}

/** `ax_layout.mjs:pointSymmetryFaults`, re-derived from the OUTPUT rather than trusted. */
export function symmetryFaults(arena, tol = 1e-6) {
  const faults = [];
  for (const c of arena.cover) {
    const px = 2 * arena.center.x - c.x, py = 2 * arena.center.y - c.y;
    if (!arena.cover.some((o) => Math.abs(o.x - px) <= tol && Math.abs(o.y - py) <= tol
      && Math.abs(o.w - c.w) <= tol && Math.abs(o.h - c.h) <= tol)) {
      faults.push(`${c.kind} (${c.x},${c.y}) has no partner at (${px},${py})`);
    }
  }
  for (const c of arena.concealment ?? []) {
    const px = 2 * arena.center.x - c.x, py = 2 * arena.center.y - c.y;
    if (!arena.concealment.some((o) => Math.abs(o.x - px) <= tol && Math.abs(o.y - py) <= tol
      && Math.abs(o.w - c.w) <= tol && Math.abs(o.h - c.h) <= tol)) faults.push(`conceal ${c.kind} (${c.x},${c.y})`);
  }
  for (const s of arena.spawns) {
    const px = 2 * arena.center.x - s.x, py = 2 * arena.center.y - s.y;
    if (!arena.spawns.some((o) => Math.abs(o.x - px) <= tol && Math.abs(o.y - py) <= tol)) faults.push(`spawn (${s.x},${s.y})`);
  }
  return faults;
}

/**
 * THE NAV GRID, at `movement.ts:navGrid`'s own rule — the cell doubles until the grid
 * fits `NAV_MAX_CELLS`. Returns the component count over passable cells and whether all
 * six spawns share one. A layout whose spawns are in different nav components has an AI
 * that literally cannot path between them, and no other gate here would say so.
 */
export function navReport(arena, size = PLAYER_SIZE) {
  const cell = navCellFor(arena.width, arena.height);
  const cols = Math.ceil(arena.width / cell), rows = Math.ceil(arena.height / cell);
  const half = size / 2;
  const passable = new Uint8Array(cols * rows);
  let open = 0;
  for (let gy = 0; gy < rows; gy++) for (let gx = 0; gx < cols; gx++) {
    const cx = (gx + 0.5) * cell, cy = (gy + 0.5) * cell;
    const ok = cx >= half && cx <= arena.width - half && cy >= half && cy <= arena.height - half
      && !arena.cover.some((o) => Math.abs(cx - o.x) < (size + o.w) / 2 && Math.abs(cy - o.y) < (size + o.h) / 2);
    if (ok) { passable[gy * cols + gx] = 1; open++; }
  }
  const label = new Int32Array(cols * rows).fill(-1);
  const q = new Int32Array(cols * rows);
  let comps = 0;
  const sizes = [];
  for (let s = 0; s < cols * rows; s++) {
    if (!passable[s] || label[s] >= 0) continue;
    const id = comps++;
    let h = 0, t = 0; q[t++] = s; label[s] = id;
    while (h < t) {
      const c = q[h++], cx = c % cols, cy = (c - cx) / cols;
      for (let oy = -1; oy <= 1; oy++) for (let ox = -1; ox <= 1; ox++) {
        if (!ox && !oy) continue;
        const nx = cx + ox, ny = cy + oy;
        if (nx < 0 || nx >= cols || ny < 0 || ny >= rows) continue;
        const ni = ny * cols + nx;
        if (!passable[ni] || label[ni] >= 0) continue;
        if (ox && oy && (!passable[cy * cols + nx] || !passable[ny * cols + cx])) continue;
        label[ni] = id; q[t++] = ni;
      }
    }
    sizes.push(t);
  }
  const at = (p) => label[Math.min(rows - 1, Math.floor(p.y / cell)) * cols + Math.min(cols - 1, Math.floor(p.x / cell))];
  const spawnComps = arena.spawns.map(at);
  return { cell, cols, rows, open, comps, sizes: sizes.sort((a, b) => b - a), spawnComps, oneComponent: new Set(spawnComps).size === 1 && spawnComps[0] >= 0 };
}

/**
 * 🔴 THE DIAGONAL NOTCH — the defect `gapFaults` is structurally blind to.
 *
 * `gapFaults` only compares two boxes that overlap on one axis, which is every
 * face-to-face gap and no corner. Two props that touch only DIAGONALLY have physical
 * gaps on neither axis, and their 21 wu collision collars can still leave a channel
 * between them: measured here at 0.5 wu between the north-wall pot stack's collar and
 * the NW freezer's, which `ap_reach` then reported as a 16 wu-deep band region on a map
 * whose 1400x1000 predecessor has ZERO.
 *
 * So the test moves into INFLATED space, which is where a fighter's centre actually
 * lives: if two inflated boxes overlap on one axis, the gap on the other must be <= 0
 * (the collars merge — a solid corner) or >= 2 nav cells (a channel the flow field can
 * see). For boxes that already overlap PHYSICALLY this is exactly `gapFaults` restated,
 * so the only new answers it gives are the diagonal ones.
 */
export function notchFaults(arena, minChannel = 2 * NAV_CELL_AT_X4) {
  const out = [];
  const B = arena.cover;
  const half = PLAYER_SIZE / 2;
  for (let i = 0; i < B.length; i++) for (let j = i + 1; j < B.length; j++) {
    const A = B[i], C = B[j];
    const ovXi = Math.min(A.x + A.w / 2 + half, C.x + C.w / 2 + half) - Math.max(A.x - A.w / 2 - half, C.x - C.w / 2 - half);
    const ovYi = Math.min(A.y + A.h / 2 + half, C.y + C.h / 2 + half) - Math.max(A.y - A.h / 2 - half, C.y - C.h / 2 - half);
    if (ovXi > 0) {
      const g = Math.abs(A.y - C.y) - (A.h + C.h) / 2 - PLAYER_SIZE;
      if (g > 0 && g < minChannel) out.push(`${A.kind}@${A.x},${A.y} / ${C.kind}@${C.x},${C.y}: ${g.toFixed(1)} wu of legal-centre channel in y (needs 0 or >= ${minChannel})`);
    }
    if (ovYi > 0) {
      const g = Math.abs(A.x - C.x) - (A.w + C.w) / 2 - PLAYER_SIZE;
      if (g > 0 && g < minChannel) out.push(`${A.kind}@${A.x},${A.y} / ${C.kind}@${C.x},${C.y}: ${g.toFixed(1)} wu of legal-centre channel in x (needs 0 or >= ${minChannel})`);
    }
  }
  return out;
}

/**
 * `ap_reach.mjs`'s DEEP BAND REGION, computed here so a layout edit is checked before it
 * is written rather than after. A cell that a `visual` wu body could stand on, that a
 * `PLAYER_SIZE` body cannot reach, and that is further from reachable space than the
 * collar can possibly be. **The shipped 1400x1000 map scores ZERO**, so zero is the bar.
 */
export function deepRegions(arena, visual = 18, L = 2) {
  const cols = Math.floor(arena.width / L), rows = Math.floor(arena.height / L);
  const reach = (size, seed) => {
    const half = size / 2;
    const legal = new Uint8Array(cols * rows);
    for (let gy = 0; gy < rows; gy++) for (let gx = 0; gx < cols; gx++) {
      const x = (gx + 0.5) * L, y = (gy + 0.5) * L;
      legal[gy * cols + gx] = x >= half && x <= arena.width - half && y >= half && y <= arena.height - half
        && !arena.cover.some((o) => Math.abs(x - o.x) < (size + o.w) / 2 && Math.abs(y - o.y) < (size + o.h) / 2) ? 1 : 0;
    }
    const seen = new Uint8Array(cols * rows);
    const q = new Int32Array(cols * rows);
    let h = 0, t = 0;
    for (const s of seed) {
      const i = Math.min(rows - 1, Math.floor(s.y / L)) * cols + Math.min(cols - 1, Math.floor(s.x / L));
      if (legal[i] && !seen[i]) { seen[i] = 1; q[t++] = i; }
    }
    while (h < t) {
      const c = q[h++], cx = c % cols, cy = (c - cx) / cols;
      for (let oy = -1; oy <= 1; oy++) for (let ox = -1; ox <= 1; ox++) {
        if (!ox && !oy) continue;
        const nx = cx + ox, ny = cy + oy;
        if (nx < 0 || nx >= cols || ny < 0 || ny >= rows) continue;
        const ni = ny * cols + nx;
        if (!legal[ni] || seen[ni]) continue;
        if (ox && oy && (!legal[cy * cols + nx] || !legal[ny * cols + cx])) continue;
        seen[ni] = 1; q[t++] = ni;
      }
    }
    return { legal, seen };
  };
  const r42 = reach(PLAYER_SIZE, arena.spawns);
  const rV = reach(visual, arena.spawns);
  const band = new Uint8Array(cols * rows);
  for (let i = 0; i < band.length; i++) if (rV.seen[i] && !r42.seen[i]) band[i] = 1;
  // Chebyshev distance from the set a real fighter can reach.
  const dist = new Int32Array(cols * rows).fill(-1);
  const q = new Int32Array(cols * rows);
  let h = 0, t = 0;
  for (let i = 0; i < band.length; i++) if (r42.seen[i]) { dist[i] = 0; q[t++] = i; }
  while (h < t) {
    const c = q[h++], cx = c % cols, cy = (c - cx) / cols;
    for (let oy = -1; oy <= 1; oy++) for (let ox = -1; ox <= 1; ox++) {
      if (!ox && !oy) continue;
      const nx = cx + ox, ny = cy + oy;
      if (nx < 0 || nx >= cols || ny < 0 || ny >= rows) continue;
      const ni = ny * cols + nx;
      if (dist[ni] >= 0) continue;
      dist[ni] = dist[c] + 1; q[t++] = ni;
    }
  }
  const collarBound = (PLAYER_SIZE - visual) / 2;
  const deep = [];
  for (let gy = 0; gy < rows; gy++) for (let gx = 0; gx < cols; gx++) {
    const i = gy * cols + gx;
    if (band[i] && dist[i] * L > collarBound + L) deep.push({ x: (gx + 0.5) * L, y: (gy + 0.5) * L, depth: dist[i] * L });
  }
  return deep;
}

export function keepout(arena) {
  return Math.max(MIN_SAFE_RADIUS, arena.maxSafeRadius * (1 - CONCEAL_ENDGAME_PROGRESS));
}

export function concealFaults(arena) {
  const faults = [];
  const ceiling = MELEE_HEAVY * 2;
  const k = keepout(arena);
  for (const b of arena.concealment) {
    if (Math.max(b.w, b.h) > ceiling) faults.push(`${b.kind}@${b.x},${b.y} is ${b.w}x${b.h} — over the ${ceiling} wu AI ceiling`);
    const near = Math.hypot(Math.max(0, Math.abs(b.x - arena.center.x) - b.w / 2), Math.max(0, Math.abs(b.y - arena.center.y) - b.h / 2));
    if (near < k) faults.push(`${b.kind}@${b.x},${b.y} nearest point ${near.toFixed(1)} < keepout ${k.toFixed(2)}`);
    // Standable: sampled on the same 2 wu lattice ap_reach --selftest §G uses.
    let inside = 0, standable = 0;
    for (let x = b.x - b.w / 2 + 1; x < b.x + b.w / 2; x += 2) for (let y = b.y - b.h / 2 + 1; y < b.y + b.h / 2; y += 2) {
      inside++;
      const ok = x >= PLAYER_SIZE / 2 && x <= arena.width - PLAYER_SIZE / 2 && y >= PLAYER_SIZE / 2 && y <= arena.height - PLAYER_SIZE / 2
        && !arena.cover.some((o) => Math.abs(x - o.x) < (PLAYER_SIZE + o.w) / 2 && Math.abs(y - o.y) < (PLAYER_SIZE + o.h) / 2);
      if (ok) standable++;
    }
    if (standable / inside < 0.95) faults.push(`${b.kind}@${b.x},${b.y} only ${(standable / inside * 100).toFixed(1)}% standable`);
    if (arena.concealment.some((o) => o !== b && Math.abs(o.x - b.x) < (o.w + b.w) / 2 && Math.abs(o.y - b.y) < (o.h + b.h) / 2)) {
      faults.push(`${b.kind}@${b.x},${b.y} overlaps another patch`);
    }
  }
  return faults;
}

