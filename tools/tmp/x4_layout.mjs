/** 🔴 The nav-cell rule. `movement.ts:navGrid` doubles the cell until the grid fits. */
export function navCellFor(width, height) {
  let cell = 10;
  while (Math.ceil(width / cell) * Math.ceil(height / cell) > 40_000) cell *= 2;
  return cell;
}
export const NAV_CELL_AT_X4 = navCellFor(W, H);
