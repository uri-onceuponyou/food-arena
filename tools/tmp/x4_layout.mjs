function emit() {
  const out = [];
  const fmt = (xE, yE, w, h, kind, yaw, build) => {
    const y = yaw !== undefined ? `, yawDeg: ${yaw}` : '';
    return `  addCover(propsGroup, cover, M, {\n`
      + `    x: ${xE}, y: ${yE}, w: ${w}, h: ${h}, kind: '${kind}'${y},\n`
      + `    build: (w, d) => ${build},\n  });`;
  };
  out.push('  // ── The central stove hub, at CENTER and at its 1400x1000 SCALE (§48 rule 2) ─');
  for (const [x, y, w, h, kind, o] of HUB) {
    const dx = x - CX, dy = y - CY;
    const ex = dx === 0 ? 'CENTER.x' : `CENTER.x ${dx < 0 ? '-' : '+'} ${Math.abs(dx)}`;
    const ey = dy === 0 ? 'CENTER.y' : `CENTER.y ${dy < 0 ? '-' : '+'} ${Math.abs(dy)}`;
    const mx = dx === 0 ? 'CENTER.x' : `CENTER.x ${dx < 0 ? '+' : '-'} ${Math.abs(dx)}`;
    const my = dy === 0 ? 'CENTER.y' : `CENTER.y ${dy < 0 ? '+' : '-'} ${Math.abs(dy)}`;
    out.push(fmt(ex, ey, w, h, kind, o.yawDeg, o.build));
    const mk = kind === 'sink_counter' ? 'fryer_counter' : kind;
    const mb = kind === 'sink_counter' ? "buildServiceCounter(M, w, d, 'fryer')" : o.build;
    out.push(fmt(mx, my, w, h, mk, kind === 'sink_counter' ? undefined : 180, mb));
  }
  for (const [x, y, w, h, kind, o] of NORTH) {
    const note = SECTION_NOTES[`${x},${y}`];
    if (note) out.push(`\n  // ── ${note} ${'─'.repeat(Math.max(3, 72 - note.length))}`);
    out.push(fmt(x, y, w, h, kind, o.yawDeg, o.build));
    out.push(fmt(`ARENA_W - ${x}`, `ARENA_H - ${y}`, w, h, kind, o.yawDeg === 180 ? undefined : 180, o.build));
  }
  return out.join('\n');
}

function emitConceal(arena) {
  const out = [];
  for (let i = 0; i < CONCEAL_NORTH.length; i++) {
    const [x, y, s, kind] = CONCEAL_NORTH[i];
    const n = i + 1;
    out.push(`  const CONCEAL_P${n}X = ${x}, CONCEAL_P${n}Y = ${y}, CONCEAL_P${n}S = ${s};`);
    out.push(`  addConceal(concealGroup, concealment, M, {\n    x: CONCEAL_P${n}X, y: CONCEAL_P${n}Y, w: CONCEAL_P${n}S, h: CONCEAL_P${n}S, kind: '${kind}',\n    build: (w, d) => buildConcealPatch(M, w, d),\n  });`);
    out.push(`  addConceal(concealGroup, concealment, M, {\n    x: ARENA_W - CONCEAL_P${n}X, y: ARENA_H - CONCEAL_P${n}Y, w: CONCEAL_P${n}S, h: CONCEAL_P${n}S,\n    kind: '${kind}', yawDeg: 180,\n    build: (w, d) => buildConcealPatch(M, w, d),\n  });`);
  }
  return out.join('\n');
}

