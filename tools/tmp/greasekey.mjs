#!/usr/bin/env node
/**
 * GREASE PUDDLE RE-KEY — price a candidate before writing it.
 *
 * ── Why ──────────────────────────────────────────────────────────────────────
 * `tools/tmp/valuescan.mjs --mode dl` measured 11 characters x 18 stations. 187 of
 * 198 clear the >=0.10 figure/ground standard (mean +0.27) and the failures are not
 * spread out — they pile onto ONE station:
 *
 *     grease_in   mean dL 0.082,   9 of 11 characters below 0.10
 *
 * i.e. one bright disc costs nine characters their worst station. That is an ARENA
 * fact wearing a character costume (`valuescan.mjs`'s `dlBelow10` gate says so out
 * loud), so it is fixed here once instead of eleven times in `src/characters/`.
 *
 * ⚠️ THE LEVER IS VALUE, NOT SATURATION. `docs/LESSONS.md` §8, falsified four times
 * on this project: the arena measures mean saturation 0.4272 against a reference
 * 0.493 and the cast is already 1.8x more saturated than its environment (0.765 vs
 * 0.425). There is nothing here to desaturate. So every candidate below moves L in
 * HSL and holds H and S, and this tool REPORTS the puddle's delivered saturation next
 * to its luma so a candidate that quietly desaturates cannot pass unnoticed.
 *
 * ⚠️ AND IT MUST STILL READ AS A HAZARD. `PUDDLE_SLOW_FACTOR` is 0.45 and terrain slow
 * is 14.6-17.2% of play; a puddle that has dissolved into the tile is a mechanic the
 * player cannot see. So `dPuddleTile` — the puddle's own delivered luma against the
 * tile immediately outside it — is reported for every candidate, and a candidate that
 * wins on `dL` by erasing the puddle loses on that column. Both numbers, every row.
 *
 * ── How ──────────────────────────────────────────────────────────────────────
 * One page load per character at `grease_in`, sim frozen, then N candidates applied
 * live to the disc material. Masks come from the DIRECT render (composer bypassed) —
 * `valuescan.mjs` records why: hiding a mesh changes 41,332 post-processed pixels
 * against a 26,173 px subject, so a post-processed matte is 58% halo. Values are read
 * from the SHIPPED post-processed frame, because that is what the player sees.
 *
 * The puddle's own pixels are found by FRONTMOST SURFACE (hide it, diff the direct
 * render), the same attribution `valuescan.mjs` uses per joint — not by projecting a
 * disc, which would need the world-to-screen scale and would silently include the
 * character standing on it.
 *
 *   node tools/tmp/headserve.mjs --worktree -- node tools/tmp/greasekey.mjs --ids hotdog,waterbottle,taco
 *   node tools/tmp/greasekey.mjs --selftest
 */
