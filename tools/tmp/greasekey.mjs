      await page.waitForTimeout(900);
      const res = await page.evaluate(CAPTURE, { playerId: id, cands, shots: SHOTS ? SHOTS.split('|') : null });
      if (res.error) { console.error(`✗ ${id}: ${res.error}`); continue; }
      all[id] = res;
      console.log(`\n${id}  disc ${res.discMaterial.colour} @ opacity ${res.discMaterial.opacity}  puddle ${res.puddlePx}px (${res.puddlePctOfFrame}% of frame)  tile ring ${res.tileRingPx}px`);
      console.log('  candidate                 hex       op      dL   dLedge   fig   grnd | puddleL puddleS  tileL  dPud-Tile');
      for (const r of res.rows) {
        console.log(`  ${r.label.padEnd(24)}${r.hex.padEnd(10)}${String(r.opacity).padStart(5)}${String(r.dL).padStart(8)}${String(r.dLedge).padStart(9)}` +
          `${String(r.figureLuma).padStart(7)}${String(r.groundLuma).padStart(7)} | ${String(r.puddleLuma).padStart(7)}${String(r.puddleSat).padStart(8)}${String(r.tileLuma).padStart(7)}${String(r.dPuddleTile).padStart(10)}`);
      }
